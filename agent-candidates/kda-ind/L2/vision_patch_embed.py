# Minimum measured win required to leave the plain route, as a ratio of plain time to the
# alternative's, required in *every* process. Derived from the repeatability of the metric
# it is applied to: across three independent processes the padded/plain ratio moved by a
# median of 0.17%, so a win that clears 2% in all three is not noise. The alternative
# constant would be the 5% ceiling of the projection-only control, but that control is a
# different and much noisier measurement, and using it discarded repeatable wins -- at
# M=25168 a 1.0221 win whose spread across processes was 0.0005.
_ROUTE_MARGIN = 1.02

# Built on first use so that importing this module never costs a cutlass import.
