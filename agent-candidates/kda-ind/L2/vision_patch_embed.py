"""Vision patch embedding for Qwen VL models.

Flattens 3D video/image patches via Conv3d weight reshaped into a linear projection.

Unified across Qwen2-VL and Qwen3-VL:
  - bias: Qwen2-VL uses bias=False, Qwen3-VL uses bias=True.

The operator is a single bfloat16 GEMM with a fused bias, so the only thing worth
tuning is which kernel runs it. Two routes exist here.

The default route calls F.linear on a zero-padded copy of the weight. PyTorch hands
cuBLAS a column-major C, which makes the library's own M our output width, and
cuBLASLt's kernel choice is erratic in that width: at 1152 it picks a good kernel on
some row counts and a poor one on others, and rounding the width up to 1200 lands on
the good kernel more often. That is the whole mechanism -- padding is a heuristic
nudge, not an improvement in arithmetic.

Profiling showed exactly where the nudge backfires. For every padded width from 1160
to 1280, cuBLASLt selects nvjet_sm100_tst_128x256_64x6_2x2_2cta for row counts M with
23040 < M <= 23552, and that kernel stalls about 1.9x more on memory than the kernel
the unpadded call gets there (long_scoreboard 12.8 against 6.8, L2 throughput 29% of
peak against 50%), costing about 13%. Because cuBLAS treats our row count as its own N
and tiles it by 256, that band is exactly ceil(M/256) in {91, 92}. Padding by 8, 48 or
128 columns produces the identical kernel, grid and stall profile there, so the padded
column count is irrelevant and no width escapes it -- the band is skipped instead. See
profile/vpe_boundary_round1/REPORT.md.

The second route is a custom CuTe DSL kernel (2-SM cooperative tcgen05, 256x192x64 MMA
tiler so 1152 = 6 x 192 divides exactly and no padding is needed, fp32 accumulation,
bias fused into the epilogue, compact output). It is correct on every captured shape
but currently runs at 0.50-0.71x of cuBLAS -- its mainloop is operand-starved at 46%
tensor-pipe utilization against cuBLAS's 90% -- so it is off by default. Enabling it
would regress every captured shape. See profile/vpe_cute_kernel_round1/REPORT.md.
"""

import torch
import torch.nn as nn

from ..L1.conv3d import Conv3d
from ..L1.linear import Matmul


# Output widths worth rounding up, mapped to the width to round up to. 1200 was the best
# of thirteen widths from 1152 to 1280 swept over all 93 captured row counts on this
# B200. Emptying this table restores exact baseline behaviour everywhere, which is the
# escape hatch if the heuristic ever moves.
_PADDED_OUTPUT_WIDTH = {1152: 1200}

# Row-count bands, per output width, where padding provokes a slower cuBLAS kernel and so
# must never be selected. NCU shows why: inside the band cuBLASLt switches to
# nvjet_sm100_tst_128x256_64x6_2x2_2cta, whose memory pipeline stalls about 1.9x more
# (long_scoreboard 12.8 against 6.8, L2 throughput 29% of peak against 50%). Because cuBLAS
# treats our row count as its own N and tiles it by 256, the band is exactly
# ceil(M/256) in {91, 92}; measured at 4-row granularity (23040 fast, 23044 slow, 23552
# slow, 23556 fast). See profile/vpe_boundary_round1/REPORT.md.
#
# This is no longer a runtime branch -- the route table below decides -- but it is the
# mechanism behind those entries, and the table builder asserts that no row count in this
# band was assigned the padded route. Keeping it here is what lets that check exist.
_UNPADDED_ROW_BANDS = {1152: ((23040, 23552),)}

# Output width the custom kernel is compiled for. Its N tiler is 192 and 1152 = 6 * 192, so
# the kernel is valid for this width and no other.
_CUSTOM_N = 1152

# Contraction depth the sweeps were run at (3 * 2 * 16 * 16). A different depth is a
# different GEMM and gets the unpadded path.
_MEASURED_INPUT_SIZE = 1536

# Operand precisions covered. float16 is deliberately absent: no evidence was gathered
# for it, and declining just means running the plain projection.
_MEASURED_DTYPES = (torch.bfloat16,)

# The measurements behind both routes are Blackwell-specific (B200, sm_100). On any other
# architecture the plain projection runs.
_MEASURED_SM = (10, 0)

# The padded projection writes an [M, padded_width] buffer and this module returns its
# leading columns, so that result's row stride is the padded width rather than the
# embedding dimension -- a view, not a compact tensor. Its values, shape, dtype and type
# are exact. Set this True to spend one extra copy on a contiguous result; at 20680 rows
# that copy costs about 21 us against the roughly 6 us the better kernel saves there, so
# it gives the win back and is off by default.
_COMPACT_OUTPUT = False

# Route names. "plain" is the unmodified projection -- exactly what the baseline does.
_PLAIN, _PADDED, _CUSTOM = "plain", "padded", "custom"

