def _build_custom_gemm():
    """Compile the custom CuTe DSL projection kernel and return a callable.

    Returns a function (x, weight, out, bias) -> None, or None if cutlass is not
    importable or compilation fails. Compilation happens once; the tensor layouts are
    marked dynamic so a single compiled kernel serves every row count.
    """
    import cutlass
    import cutlass.cute as cute
    import cutlass.pipeline as pipeline
    import cutlass.utils as utils
    import cutlass.utils.blackwell_helpers as sm100_utils
    from cutlass.cute.nvgpu import cpasync, tcgen05
    from cutlass.cute.runtime import from_dlpack

    IO_DTYPE = cutlass.BFloat16
    ACC_DTYPE = cutlass.Float32
    USE_2CTA = True
    CLUSTER_SHAPE_MNK = (2, 1, 1)
    # 1152 = 6 * 192, so the N dimension is covered exactly with no tail tile.
    MMA_INST_SHAPE_MNK = (256, 192, 16)
    MMA_TILER_MNK = (256, 192, 64)
    THREADS_IN_EPILOGUE = 128
    AB_STAGES = 6
    EPI_STAGES = 2
    ACC_STAGES = 1


    @cute.struct
    class SharedStorage:
        ab_mbar_ptr: cute.struct.MemRange[cutlass.Int64, AB_STAGES * 2]
        acc_mbar_ptr: cute.struct.MemRange[cutlass.Int64, ACC_STAGES * 2]
        tmem_dealloc_mbar: cutlass.Int64
        tmem_holding_buffer: cutlass.Int32


    @cute.kernel()
    def gemm_bias_kernel(
        tiled_mma: cute.TiledMma,
        tma_atom_a: cute.CopyAtom,
        mA_mkl: cute.Tensor,
        tma_atom_b: cute.CopyAtom,
        mB_nkl: cute.Tensor,
        tma_atom_c: cute.CopyAtom,
        mC_mnl: cute.Tensor,
        mBias: cute.Tensor,
        a_smem_layout: cute.ComposedLayout,
        b_smem_layout: cute.ComposedLayout,
        c_smem_layout_kind: cutlass.Constexpr,
        epi_smem_layout_staged: cute.ComposedLayout,
        epi_tile: cute.Tile,
        cta_layout_vmnk: cute.Layout,
    ):
        warp_idx = cute.arch.make_warp_uniform(cute.arch.warp_idx())
        tidx, _, _ = cute.arch.thread_idx()
        bidx, bidy, _ = cute.arch.block_idx()

        cta_rank_in_cluster = cute.arch.block_idx_in_cluster()
        cta_in_cluster_coord_vmnk = cta_layout_vmnk.get_flat_coord(cta_rank_in_cluster)

        mma_coord_vmnk = (
            bidx % cute.size(cta_layout_vmnk, mode=[0]),
            bidx // cute.size(cta_layout_vmnk, mode=[0]),
            bidy,
            None,
        )
        mma_coord_mnk = mma_coord_vmnk[1:]
        is_leader_cta = mma_coord_vmnk[0] == 0

        epilogue_warp_ids = (0, 1, 2, 3)
        mma_warp_id = 4
        tma_warp_id = 5

        smem = cutlass.utils.SmemAllocator()
        storage = smem.allocate(SharedStorage)
        sA = smem.allocate_tensor(
            element_type=IO_DTYPE, layout=a_smem_layout.outer,
            byte_alignment=128, swizzle=a_smem_layout.inner)
        sB = smem.allocate_tensor(
            element_type=IO_DTYPE, layout=b_smem_layout.outer,
            byte_alignment=128, swizzle=b_smem_layout.inner)
        sC = smem.allocate_tensor(
            element_type=IO_DTYPE, layout=epi_smem_layout_staged.outer,
            byte_alignment=128, swizzle=epi_smem_layout_staged.inner)

        if warp_idx == tma_warp_id:
            cpasync.prefetch_descriptor(tma_atom_a)
            cpasync.prefetch_descriptor(tma_atom_b)
            cpasync.prefetch_descriptor(tma_atom_c)

        num_mcast_participants = (
            cute.size(cta_layout_vmnk, mode=[1]) + cute.size(cta_layout_vmnk, mode=[2]) - 1
        )
        tma_mcast_mask_a = cpasync.create_tma_multicast_mask(
            cta_layout_vmnk, cta_in_cluster_coord_vmnk, mcast_mode=2)
        tma_mcast_mask_b = cpasync.create_tma_multicast_mask(
            cta_layout_vmnk, cta_in_cluster_coord_vmnk, mcast_mode=1)

        gA = cute.local_tile(mA_mkl, MMA_TILER_MNK, mma_coord_mnk, proj=(1, None, 1))
        gB = cute.local_tile(mB_nkl, MMA_TILER_MNK, mma_coord_mnk, proj=(None, 1, 1))
        gC = cute.local_tile(mC_mnl, MMA_TILER_MNK, mma_coord_mnk, proj=(1, 1, None))

        thr_mma = tiled_mma.get_slice(mma_coord_vmnk[0])
        tCgA = thr_mma.partition_A(gA)
        tCgB = thr_mma.partition_B(gB)
        tCgC = thr_mma.partition_C(gC)

        # A view of the per-column bias shaped like C but with a zero row stride, so
        # every row reads the same 1152 values. Tiling it exactly like gC makes the
        # epilogue partitioning line up element for element, which is what lets the
        # bias be applied in the epilogue rather than in a second pass over the output.
        mBias_bcast = cute.make_tensor(
            mBias.iterator, cute.make_layout(mC_mnl.shape, stride=(0, 1)))
        gBias = cute.local_tile(mBias_bcast, MMA_TILER_MNK, mma_coord_mnk, proj=(1, 1, None))
        tCgBias = thr_mma.partition_C(gBias)

        tCrA = tiled_mma.make_fragment_A(sA)
        tCrB = tiled_mma.make_fragment_B(sB)
        acc_shape = tiled_mma.partition_shape_C(MMA_TILER_MNK[:2])
        tCtAcc_fake = tiled_mma.make_fragment_C(acc_shape)

        epilogue_sync_barrier = pipeline.NamedBarrier(
            barrier_id=1, num_threads=THREADS_IN_EPILOGUE)
        tmem_alloc_barrier = pipeline.NamedBarrier(
            barrier_id=2, num_threads=32 * len((mma_warp_id, *epilogue_warp_ids)))
        tmem = utils.TmemAllocator(
            storage.tmem_holding_buffer,
            barrier_for_retrieve=tmem_alloc_barrier,
            allocator_warp_id=epilogue_warp_ids[0],
            is_two_cta=USE_2CTA,
            two_cta_tmem_dealloc_mbar_ptr=storage.tmem_dealloc_mbar,
        )

        tAsA, tAgA = cpasync.tma_partition(
            tma_atom_a, cta_in_cluster_coord_vmnk[2],
            cute.make_layout(cute.size(cta_layout_vmnk, mode=[2])),
            cute.group_modes(sA, 0, 3), cute.group_modes(tCgA, 0, 3))
        tBsB, tBgB = cpasync.tma_partition(
            tma_atom_b, cta_in_cluster_coord_vmnk[1],
            cute.make_layout(cute.size(cta_layout_vmnk, mode=[1])),
            cute.group_modes(sB, 0, 3), cute.group_modes(tCgB, 0, 3))

        tCgC_epi = cute.flat_divide(tCgC[((None, None), 0, 0)], epi_tile)
        tCgBias_epi = cute.flat_divide(tCgBias[((None, None), 0, 0)], epi_tile)
        tCsC, tCgC_tma = cpasync.tma_partition(
            tma_atom_c, 0, cute.make_layout(1),
            cute.group_modes(sC, 0, 2), cute.group_modes(tCgC_epi, 0, 2))

        num_tma_copy_bytes = (
            cute.size_in_bytes(IO_DTYPE, cute.select(a_smem_layout, mode=[0, 1, 2]))
            + cute.size_in_bytes(IO_DTYPE, cute.select(b_smem_layout, mode=[0, 1, 2]))
        ) * cute.size(cta_layout_vmnk, mode=[0])

        ab_producer, ab_consumer = pipeline.PipelineTmaUmma.create(
            barrier_storage=storage.ab_mbar_ptr.data_ptr(),
            num_stages=AB_STAGES,
            producer_group=pipeline.CooperativeGroup(pipeline.Agent.Thread),
            consumer_group=pipeline.CooperativeGroup(
                pipeline.Agent.Thread, size=num_mcast_participants),
            tx_count=num_tma_copy_bytes,
            cta_layout_vmnk=cta_layout_vmnk,
        ).make_participants()

        acc_producer, acc_consumer = pipeline.PipelineUmmaAsync.create(
            barrier_storage=storage.acc_mbar_ptr.data_ptr(),
            num_stages=ACC_STAGES,
            producer_group=pipeline.CooperativeGroup(pipeline.Agent.Thread),
            consumer_group=pipeline.CooperativeGroup(
                pipeline.Agent.Thread,
                size=cute.size(cta_layout_vmnk, mode=[0]) * len(epilogue_warp_ids)),
            cta_layout_vmnk=cta_layout_vmnk,
        ).make_participants()

        num_k_tiles = cute.size(gA, mode=[2])

        if warp_idx == tma_warp_id:
            for k_tile_idx in range(num_k_tiles):
                handle = ab_producer.acquire_and_advance()
                cute.copy(tma_atom_a, tAgA[(None, k_tile_idx)],
                          tAsA[(None, handle.index)],
                          tma_bar_ptr=handle.barrier, mcast_mask=tma_mcast_mask_a)
                cute.copy(tma_atom_b, tBgB[(None, k_tile_idx)],
                          tBsB[(None, handle.index)],
                          tma_bar_ptr=handle.barrier, mcast_mask=tma_mcast_mask_b)
            ab_producer.tail()

        elif warp_idx == mma_warp_id:
            tmem.wait_for_alloc()
            tmem_ptr = tmem.retrieve_ptr(ACC_DTYPE)
            tCtAcc = cute.make_tensor(tmem_ptr, tCtAcc_fake.layout)
            if is_leader_cta:
                acc_empty = acc_producer.acquire_and_advance()
                for k_tile_idx in range(num_k_tiles):
                    handle = ab_consumer.wait_and_advance()
                    tiled_mma.set(tcgen05.Field.ACCUMULATE, k_tile_idx != 0)
                    crd = (None, None, None, handle.index)
                    cute.gemm(tiled_mma, tCtAcc, tCrA[crd], tCrB[crd], tCtAcc)
                    handle.release()
                acc_empty.commit()

        elif warp_idx < mma_warp_id:
            tmem.allocate(512)
            tmem.wait_for_alloc()
            tmem_ptr = tmem.retrieve_ptr(ACC_DTYPE)
            tCtAcc = cute.make_tensor(tmem_ptr, tCtAcc_fake.layout)

            epilogue_pipeline = pipeline.PipelineTmaStore.create(
                num_stages=EPI_STAGES,
                producer_group=pipeline.CooperativeGroup(pipeline.Agent.Thread, size=128),
            )
            acc_consumer.wait_and_advance()

            copy_atom_t2r = cute.make_copy_atom(
                tcgen05.Ld16x256bOp(tcgen05.Repetition.x8)
                if MMA_TILER_MNK[0] == 64
                else tcgen05.Ld32x32bOp(tcgen05.Repetition.x32),
                cutlass.Float32,
            )
            tCtAcc_epi = cute.flat_divide(tCtAcc[((None, None), 0, 0)], epi_tile)
            tiled_copy_t2r = tcgen05.make_tmem_copy(
                copy_atom_t2r, tCtAcc_epi[(None, None, 0, 0)])
            thr_copy_t2r = tiled_copy_t2r.get_slice(tidx)
            tTR_tAcc = thr_copy_t2r.partition_S(tCtAcc_epi)
            tTR_gC = thr_copy_t2r.partition_D(tCgC_epi)
            tTR_bias = thr_copy_t2r.partition_D(tCgBias_epi)
            tTR_rAcc = cute.make_rmem_tensor(
                tTR_gC[(None, None, None, 0, 0)].shape, cutlass.Float32)
            tTR_tAcc = cute.group_modes(tTR_tAcc, 3, cute.rank(tTR_tAcc))
            tTR_bias = cute.group_modes(tTR_bias, 3, cute.rank(tTR_bias))

            copy_atom_r2s = sm100_utils.get_smem_store_op(
                c_smem_layout_kind, cutlass.Float32, cutlass.Float32, tiled_copy_t2r)
            tiled_copy_r2s = cute.make_tiled_copy_D(copy_atom_r2s, tiled_copy_t2r)
            thr_copy_r2s = tiled_copy_r2s.get_slice(tidx)
            tRS_sC = thr_copy_r2s.partition_D(sC)
            tRS_rAcc = tiled_copy_r2s.retile(tTR_rAcc)
            tRS_rC = cute.make_rmem_tensor(tRS_rAcc.shape, IO_DTYPE)
            tTR_rBias = cute.make_rmem_tensor(tTR_rAcc.shape, IO_DTYPE)

            tCgC_grouped = cute.group_modes(tCgC_tma, 1, cute.rank(tCgC_tma))
            subtile_cnt = cute.size(tTR_tAcc.shape, mode=[3])

            for subtile_idx in cutlass.range(subtile_cnt):
                cute.copy(tiled_copy_t2r,
                          tTR_tAcc[(None, None, None, subtile_idx)], tTR_rAcc)

                # Fused bias. Copied into registers as one vector op per subtile rather
                # than one global load per element -- the broadcast view is contiguous along
                # N inside a subtile, so this vectorizes -- then added to the fp32
                # accumulator before the narrowing cast, as cuBLASLt's epilogue does.
                cute.autovec_copy(tTR_bias[(None, None, None, subtile_idx)], tTR_rBias)
                tTR_rAcc.store(tTR_rAcc.load() + tTR_rBias.load().to(cutlass.Float32))

                c_buffer = subtile_idx % EPI_STAGES
                tRS_sC_slice = tRS_sC[(None, None, None, c_buffer)]
                tRS_rC.store(tRS_rAcc.load().to(IO_DTYPE))
                cute.copy(tiled_copy_r2s, tRS_rC, tRS_sC_slice)

                cute.arch.fence_view_async_shared()
                epilogue_sync_barrier.arrive_and_wait()
                if warp_idx == epilogue_warp_ids[0]:
                    cute.copy(tma_atom_c, tCsC[(None, c_buffer)],
                              tCgC_grouped[(None, subtile_idx)])
                    epilogue_pipeline.producer_commit()
                    epilogue_pipeline.producer_acquire()
                epilogue_sync_barrier.arrive_and_wait()

            epilogue_pipeline.producer_tail()
            tmem.relinquish_alloc_permit()
            tmem.free(tmem_ptr)


    @cute.jit
    def gemm_bias(a: cute.Tensor, b: cute.Tensor, c: cute.Tensor, bias: cute.Tensor):
        op = tcgen05.MmaF16BF16Op(
            IO_DTYPE, ACC_DTYPE, MMA_INST_SHAPE_MNK,
            tcgen05.CtaGroup.TWO if USE_2CTA else tcgen05.CtaGroup.ONE,
            tcgen05.OperandSource.SMEM,
            tcgen05.OperandMajorMode.K,
            tcgen05.OperandMajorMode.K,
        )
        tiled_mma = cute.make_tiled_mma(op)

        a_smem_layout = sm100_utils.make_smem_layout_a(
            tiled_mma, MMA_TILER_MNK, a.element_type, AB_STAGES)
        b_smem_layout = sm100_utils.make_smem_layout_b(
            tiled_mma, MMA_TILER_MNK, b.element_type, AB_STAGES)
        c_smem_layout_kind = utils.LayoutEnum.from_tensor(c)

        cta_layout_mnk = cute.make_layout(CLUSTER_SHAPE_MNK)
        cta_layout_vmnk = cute.tiled_divide(cta_layout_mnk, (tiled_mma.thr_id,))

        load_op = cpasync.CopyBulkTensorTileG2SMulticastOp(
            tcgen05.CtaGroup.TWO if USE_2CTA else tcgen05.CtaGroup.ONE)
        a_tma_atom, a_tma_tensor = cute.nvgpu.make_tiled_tma_atom_A(
            load_op, a, cute.slice_(a_smem_layout, (None, None, None, 0)),
            MMA_TILER_MNK, tiled_mma, cta_layout_vmnk.shape)
        b_tma_atom, b_tma_tensor = cute.nvgpu.make_tiled_tma_atom_B(
            load_op, b, cute.slice_(b_smem_layout, (None, None, None, 0)),
            MMA_TILER_MNK, tiled_mma, cta_layout_vmnk.shape)

        cta_tile_shape_mnk = (
            MMA_TILER_MNK[0] // cute.size(tiled_mma.thr_id),
            MMA_TILER_MNK[1],
            MMA_TILER_MNK[2],
        )
        epi_tile = utils.compute_epilogue_tile_shape(
            cta_tile_shape_mnk, USE_2CTA, c_smem_layout_kind, IO_DTYPE)
        epi_smem_layout_staged = sm100_utils.make_smem_layout_epi(
            IO_DTYPE, c_smem_layout_kind, epi_tile, EPI_STAGES)
        c_tma_atom, c_tma_tensor = cpasync.make_tiled_tma_atom(
            cpasync.CopyBulkTensorTileS2GOp(), c,
            cute.slice_(epi_smem_layout_staged, (None, None, 0)), epi_tile)

        # ceil_div on M, then round up to the cluster: the ragged tail tile is handled by
        # TMA rather than by shrinking the grid.
        grid_shape = cute.round_up(
            (
                cute.ceil_div(c.layout.shape[0],
                              MMA_TILER_MNK[0] // (2 if USE_2CTA else 1)),
                cute.ceil_div(c.layout.shape[1], MMA_TILER_MNK[1]),
                1,
            ),
            CLUSTER_SHAPE_MNK,
        )

        gemm_bias_kernel(
            tiled_mma, a_tma_atom, a_tma_tensor, b_tma_atom, b_tma_tensor,
            c_tma_atom, c_tma_tensor, bias,
            a_smem_layout, b_smem_layout, c_smem_layout_kind,
            epi_smem_layout_staged, epi_tile, cta_layout_vmnk,
        ).launch(grid=grid_shape, block=[192, 1, 1], cluster=CLUSTER_SHAPE_MNK)

    # detach() is a free view; from_dlpack refuses to export a tensor that
    # requires grad, and the parameters do even when gradients are disabled.
    dyn = lambda t: from_dlpack(t.detach()).mark_layout_dynamic()
    warm_x = torch.zeros(MMA_TILER_MNK[0], _MEASURED_INPUT_SIZE,
                         device="cuda", dtype=torch.bfloat16)
    warm_c = torch.zeros(MMA_TILER_MNK[0], 1152, device="cuda", dtype=torch.bfloat16)
    warm_w = torch.zeros(1152, _MEASURED_INPUT_SIZE, device="cuda", dtype=torch.bfloat16)
    warm_b = torch.zeros(1152, device="cuda", dtype=torch.bfloat16)
    compiled = cute.compile(gemm_bias, dyn(warm_x), dyn(warm_w), dyn(warm_c), dyn(warm_b))

    def run(x, weight, out, bias):
        compiled(dyn(x), dyn(weight), dyn(out), dyn(bias))

    return run


class VisionPatchEmbed(nn.Module):
    def __init__(self, patch_size: int, temporal_patch_size: int,
                 in_channels: int, embed_dim: int, bias: bool = False):
        super().__init__()
        self.embed_dim = embed_dim
        self.input_size = in_channels * temporal_patch_size * patch_size * patch_size
        kernel = (temporal_patch_size, patch_size, patch_size)
        self.proj = Conv3d(in_channels, embed_dim, kernel, bias=bias)
        self.linear = Matmul()
        # Nothing may be derived from proj.weight here. Callers are free to cast the
        # parameters to another dtype, re-initialize them in place, or copy reference
        # weights in after construction, so anything precomputed now would hold
        # pre-load values. The padded copy is built on the first forward instead.
        self._padded = None

    @staticmethod
    def _source_key(weight, bias):
        """Identity of the parameters a padded copy was built from.

        Storage address alone is not enough: an in-place copy into the parameters
        leaves the address unchanged while changing the contents, which the version
        counter catches. Views share their base's version counter, so writing through
        one is caught too.

        Three kinds of mutation escape this and are NOT supported: writing through
        ``param.data`` (``w.data.copy_(...)`` and friends leave the version counter
        untouched), writing the storage from a raw pointer or a custom kernel, and
        mutating the padded tensors this cache owns. There is no cheap correct fix --
        ``.data`` bypasses the version counter by design and detecting it would need a
        content comparison on every forward -- so it is documented rather than papered
        over. Rebinding ``param.data`` to a different tensor is fine: that changes the
        address. The custom kernel route needs no packed copy and so has no such gap.
        """
        key = (weight.data_ptr(), weight._version, weight.dtype, weight.device,
               tuple(weight.shape), weight.stride())
        if bias is None:
            return key + (None,)
        return key + (bias.data_ptr(), bias._version, bias.dtype, bias.device,
                      tuple(bias.shape), bias.stride())

    @staticmethod
    def _grad_active(weight, bias):
        """True when a graph could be being built, in which case neither optimized route
        may run: a detached packed copy cannot carry gradients back to the real
        parameters, and the custom kernel is not differentiable at all."""
        return torch.is_grad_enabled() and (
            weight.requires_grad or (bias is not None and bias.requires_grad))

    @staticmethod
    def _padded_supported(weight, bias):
        """Exact signature the padding measurements were taken on."""
        if weight.dim() != 2:
            return False
        width, input_size = weight.shape
        return (width in _PADDED_OUTPUT_WIDTH
                and input_size == _MEASURED_INPUT_SIZE
                and weight.dtype in _MEASURED_DTYPES
                and weight.device.type == "cuda"
                and torch.cuda.get_device_capability(weight.device) == _MEASURED_SM
                and (bias is None or (bias.dim() == 1 and bias.shape[0] == width
                                      and bias.dtype == weight.dtype
                                      and bias.device == weight.device))
                and not VisionPatchEmbed._grad_active(weight, bias))

    @staticmethod
    def _custom_supported(x, weight, bias):
        """Exact signature the custom kernel was written and measured for.

        Stricter than the padded gate on purpose: the kernel's N tiler is compiled to
        _CUSTOM_N and its operands go straight to TMA descriptors, so anything about the
        shape, dtype, device or layout that it does not expect must not reach it. Every
        clause here is covered by a negative test.
        """
        if weight.dim() != 2 or x.dim() != 2 or bias is None:
            return False
        width, input_size = weight.shape
        return (width == _CUSTOM_N
                and input_size == _MEASURED_INPUT_SIZE
                and x.shape[1] == input_size
                and weight.dtype == torch.bfloat16
                and x.dtype == torch.bfloat16
                and bias.dtype == torch.bfloat16
                and bias.dim() == 1 and bias.shape[0] == width
                and weight.device.type == "cuda"
                and x.device == weight.device
                and bias.device == weight.device
                and torch.cuda.get_device_capability(weight.device) == _MEASURED_SM
                and x.is_contiguous() and weight.is_contiguous()
                and bias.is_contiguous()
                and not VisionPatchEmbed._grad_active(weight, bias))

    def _padded_projection(self, weight, bias):
        """Build (or reuse) the zero-padded weight and bias. Callers must have checked
        _padded_supported first; the row-count decision lives in the route table."""
        width, input_size = weight.shape
        padded_width = _PADDED_OUTPUT_WIDTH[width]

        key = self._source_key(weight, bias)
        cached = self._padded
        if cached is not None and cached[0] == key:
            return cached[3], cached[4], width

        padded_weight = weight.new_zeros((padded_width, input_size))
        padded_weight[:width].copy_(weight)
        if bias is None:
            padded_bias = None
        else:
            padded_bias = bias.new_zeros((padded_width,))
            padded_bias[:width].copy_(bias)
        # Holding the sources keeps their storage alive, so the caching allocator can
        # never hand a freed address to a different tensor whose version counter happens
        # to match this key and alias a stale entry. The parameters outlive the module
        # anyway, so this costs nothing.
        self._padded = (key, weight, bias, padded_weight, padded_bias)
        return padded_weight, padded_bias, width

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        x = x.view(x.shape[0], self.input_size)
        weight = self.proj.weight.view(self.embed_dim, self.input_size)
        bias = self.proj.bias
        rows = x.shape[0]

        # A table lookup, not a measurement: nothing here times anything, and a row count
        # that was never measured falls through to the plain projection.
        route = _ROUTE_TABLE.get(rows, _PLAIN)

        if route == _CUSTOM and self._custom_supported(x, weight, bias):
            run = _custom_projection()
            if run is not None:
                out = torch.empty(rows, self.embed_dim,
                                  device=x.device, dtype=x.dtype)
                run(x, weight, out, bias)
                self._padded = None
                return out

        if route == _PADDED and self._padded_supported(weight, bias):
            padded = self._padded_projection(weight, bias)
            if padded is not None:
                padded_weight, padded_bias, width = padded
                # The padded rows are exactly zero, so each returned column's reduction is
                # independent of them and equals the unpadded projection in exact
                # arithmetic. The padded call does select a different kernel, whose
                # accumulation order need not match, so the low bits may differ.
                out = self.linear(x, padded_weight, padded_bias)[:, :width]
                return out.contiguous() if _COMPACT_OUTPUT else out

        # Plain projection: byte-for-byte what the baseline computes. Release any packed
        # copy so an unsupported device or dtype move cannot retain the old device's
        # tensors.
        self._padded = None
        return self.linear(x, weight, bias)

def _custom_projection():
    """The compiled custom kernel, built on first use. None if unavailable."""
    global _custom_gemm, _custom_gemm_failed
    if _custom_gemm is None and not _custom_gemm_failed:
        try:
            _custom_gemm = _build_custom_gemm()
        except Exception:
            _custom_gemm_failed = True
    return _custom_gemm
